def ripple_unipolar(vbus, va, R, I, L, Ts):
    """Peak-to-peak ripple of a locked phase with centre-aligned PWM, a = va / vbus:
    the phase sees vbus during two intervals of |a| Ts / 2 per period."""
    a = abs(va) / vbus
    return (vbus - R * abs(I)) * a * Ts / 2 / L


def ref_hold(I, phi):
    return lambda t: (I, phi, 0.0, 0.0)


def ref_speed(I, rev_s, m, t_ramp=0.05):
    """Constant current, electrical angle ramps up to rev_s in t_ramp, then constant."""
    p = m["Ns"] / 4
    w_end = 2 * math.pi * rev_s

    def f(t):
        if t < t_ramp:
            w = w_end * t / t_ramp
            th = w_end * t * t / (2 * t_ramp)
        else:
            w = w_end
            th = w_end * t_ramp / 2 + w_end * (t - t_ramp)
        return I, p * th, w, 0.0
    return f


def stage_board(topo, stage, **sw):
    return dict(BOARD, topology=topo, stage=stage, sw=dict(STAGE, **sw))


def test_t10(m, c):
    ok = True
    Ts = 1.0 / BOARD["fs"]
    vbus = BOARD["vbus"]
    # T10a ideal switches (no dead time, no Rds, no diode): sampled current = averaged
    # model, ripple = analytic value
    for topo in ("full", "shared"):
        ideal = stage_board(topo, "switching", dead_ns=0.0, rds_on=0.0, vd=0.0)
        log_s, ext = sim_closed_loop(m, ideal, c, ref_hold(2.0, 0.6), 0.02, locked=True)
        log_a, _ = sim_closed_loop(m, dict(ideal, stage="avg"), c, ref_hold(2.0, 0.6), 0.02,
                                   locked=True)
        diff = np.max(np.abs(log_s[:, 1:3] - log_a[:, 1:3]))
        log_s, ext = sim_closed_loop(m, ideal, c, ref_hold(2.0, 0.0), 0.02, locked=True)
        last = ext[-200:]
        pp = np.mean(last[:, 1] - last[:, 0])
        ana = ripple_unipolar(vbus, m["R"] * 2.0, m["R"], 2.0, m["L"], Ts)
        ok &= check(f"T10 {topo}: ideal switching = averaged model, ripple as analytic",
                    diff < 1e-3 and abs(pp - ana) / ana < 0.05,
                    f"max sampled difference {diff * 1e3:.4f} mA, ripple {pp * 1e3:.2f} mA p-p "
                    f"(analytic {ana * 1e3:.2f} mA)")
    # T10b dead time: phase voltage error -2 sign(i) (vbus + 2 vd) td / Ts (two legs)
    sw = stage_board("full", "switching")
    td = sw["sw"]["dead_ns"] * 1e-9
    vd = sw["sw"]["vd"]
    want = 2 * (vbus + 2 * vd) * td / Ts
    worst = 0.0
    for I in (2.0, -2.0):
        log_s, ext = sim_closed_loop(m, sw, c, ref_hold(I, 0.0), 0.02, locked=True)
        sel = slice(-200, None)
        dv = ext[sel, 4] - log_s[sel, 7]            # period mean - commanded
        resid = dv + np.sign(I) * want + 2 * sw["sw"]["rds_on"] * log_s[sel, 1]
        worst = max(worst, float(np.max(np.abs(resid))))
    ok &= check("T10 dead time: phase voltage error = -2 sign(i) (Vbus + 2 Vd) td / Ts",
                worst < 0.01 * want,
                f"expected {want:.3f} V at td = {td * 1e9:.0f} ns, max deviation "
                f"{worst * 1e3:.2f} mV")
    # T10c closed loop at 4 rev/s with the real stage: synchronous, peaks below the trip
    for topo in ("full", "shared"):
        log_s, ext = sim_closed_loop(m, stage_board(topo, "switching"), c,
                                     ref_speed(2.0, 4.0, m), 0.15)
        log_a, _ = sim_closed_loop(m, stage_board(topo, "avg"), c, ref_speed(2.0, 4.0, m), 0.15)
        sel = log_s[:, 0] >= 0.1
        p = m["Ns"] / 4
        lag_s = np.degrees(np.max(np.abs(log_s[sel, 11] - p * log_s[sel, 4])))
        err_s = np.sqrt(np.mean((log_s[sel, 1] - log_s[sel, 5]) ** 2 +
                                (log_s[sel, 2] - log_s[sel, 6]) ** 2))
        err_a = np.sqrt(np.mean((log_a[sel, 1] - log_a[sel, 5]) ** 2 +
                                (log_a[sel, 2] - log_a[sel, 6]) ** 2))
        peak = np.max(np.abs(ext[:, :4]))
        ok &= check(f"T10 {topo} 4 rev/s with dead time: synchronous, peak below the trip",
                    lag_s < 90 and peak < 3.5,
                    f"peak {peak:.3f} A, max load angle {lag_s:.1f} deg, rms tracking error "
                    f"{err_s * 1e3:.1f} mA (averaged {err_a * 1e3:.1f} mA)")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    ok = test_t10(MOTOR, CTRL)
    if args.write:
        brd = stage_board("shared", "switching")
        log, ext = sim_closed_loop(MOTOR, brd, CTRL, ref_speed(2.0, 4.0, MOTOR, 0.01), 0.02)
        path = os.path.join(ROOT, "tests", "reference", "x04_switching_shared.csv")
        with open(path, "w", newline="\n") as f:
            f.write("# X04 reference: closed current loop, switching shared-leg stage, 24 V, "
                    f"20 kHz, dead time {STAGE['dead_ns']:.1f} ns, R {STAGE['rds_on'] * 1e3:.3f} "
                    f"mOhm, Vd {STAGE['vd']:.3f} V (params/stage_esc1_spice.json), 2 A, ramp to "
                    "4 rev/s in 10 ms, every 10th period. Generated by tools/ref_switching.py.\n")
            f.write("t_s,iA_A,iB_A,w_rad_s,theta_rad,iAmax_A,iBmax_A,vA_mean_V,vB_mean_V\n")
            for k in range(0, len(log), 10):
                r, e = log[k], ext[k]
                f.write(f"{r[0]:.8f},{r[1]:.12e},{r[2]:.12e},{r[3]:.12e},{r[4]:.12e},"
                        f"{e[1]:.12e},{e[3]:.12e},{e[4]:.12e},{e[5]:.12e}\n")
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
