# Same values as params/board_bg431b_esc1.sci: switching stage from ngspice
# (params/stage_esc1_spice.json, generated by sfs-stepper-power-spice)
with open(os.path.join(ROOT, "params", "stage_esc1_spice.json")) as _f:
    _SPICE = json.load(_f)
STAGE = dict(
    dead_ns=_SPICE["dead_eff_ns"],  # ns, effective dead time
    rds_on=_SPICE["r_leg"],         # Ohm, leg resistance (switch, shunt)
    vd=_SPICE["vd"],                # V, body diode at 2 A
    nstep=16,                       # RK4 steps per PWM period (more at the switching instants)
)

LOW, HIGH, DEAD = 0, 1, 2


def leg_events(d, Ts, td):
    """Switching events of one leg in one period [(t_start, state)], period starts at the
    counter peak (all low-side switches on: the current sampling instant).

    Centre-aligned PWM: high side on in [Ts/2 (1 - d), Ts/2 (1 + d)]; the timer delays
    every turn-on by td (dead time). A pulse shorter than td disappears.
    """
    if d >= 1.0:
        return [(0.0, HIGH)]
    if d <= 0.0:
        return [(0.0, LOW)]
    t1 = Ts / 2 * (1.0 - d)
    t2 = Ts / 2 * (1.0 + d)
    ev = [(0.0, LOW), (t1, DEAD)]
    if t1 + td < t2:
        ev.append((t1 + td, HIGH))
    ev.append((t2, DEAD))
    if t2 + td < Ts:
        ev.append((t2 + td, LOW))
    return ev


def leg_state(ev, t):
    s = ev[0][1]
    for te, st in ev:
        if te <= t:
            s = st
    return s


def leg_voltage(state, i_leg, vbus, sg):
    """Leg output voltage referred to the negative rail; i_leg > 0 flows out of the leg."""
    if state == HIGH:
        return vbus - i_leg * sg["rds_on"]
    if state == LOW:
        return -i_leg * sg["rds_on"]
    if state == DEAD:
        return -sg["vd"] if i_leg >= 0.0 else vbus + sg["vd"]
    return 0.0


def phase_voltages(states, x, vbus, topology, sg):
    iA, iB = x[0], x[1]
    if topology == "full":
        il = (iA, -iA, iB, -iB)
        v = [leg_voltage(states[k], il[k], vbus, sg) for k in range(4)]
        return v[0] - v[1], v[2] - v[3]
    il = (iA, iB, -(iA + iB))
    v = [leg_voltage(states[k], il[k], vbus, sg) for k in range(3)]
    return v[0] - v[2], v[1] - v[2]


def period_sw(x, duty, enabled, TL, m, vbus, topology, sg, Ts, locked):
    """One PWM period of the switching stage. Returns (x, [iAmin iAmax iBmin iBmax vA vB])
    with vA, vB the phase voltages averaged over the period."""
    td = sg["dead_ns"] * 1e-9
    nleg = len(duty)
    if enabled:
        evs = [leg_events(duty[k], Ts, td) for k in range(nleg)]
    else:
        evs = [[(0.0, DEAD)] for _ in range(nleg)]
    bps = sorted(set([0.0, Ts] + [te for ev in evs for te, _ in ev if 0.0 < te < Ts]))
    hmax = Ts / sg["nstep"]
    ext = [x[0], x[0], x[1], x[1], 0.0, 0.0]
    for j in range(len(bps) - 1):
        ta, tb = bps[j], bps[j + 1]
        states = [leg_state(evs[k], ta) for k in range(nleg)]
        n = int(math.ceil((tb - ta) / hmax - 1e-9))
        h = (tb - ta) / n
        for _ in range(n):
            vA, vB = phase_voltages(states, x, vbus, topology, sg)
            x = rk4(x, (vA, vB, TL), m, h, locked)
            ext[4] += vA * h
            ext[5] += vB * h
            ext[0] = min(ext[0], x[0])
            ext[1] = max(ext[1], x[0])
            ext[2] = min(ext[2], x[1])
            ext[3] = max(ext[3], x[1])
    ext[4] /= Ts
    ext[5] /= Ts
    return x, ext


def sim_closed_loop(m, brd, c, ref, T, locked=False):
    """As ref_ctrl.sim_closed_loop; brd["stage"] = "avg" or "switching".
    Returns (log, ext): ext per period [iAmin iAmax iBmin iBmax vA vB] (switching only)."""
    g = ctrl_gains(m, c, brd["fs"])
    Ts = g["Ts"]
    N = int(round(T / Ts))
    x = np.zeros(4)
    integ = [0.0, 0.0]
    v_hold = (0.0, 0.0)
    nleg = 4 if brd["topology"] == "full" else 3
    d_hold = [0.0] * nleg
    en_hold = False
    log = np.zeros((N, 12))
    ext = np.zeros((N, 6))
    for k in range(N):
        t = k * Ts
        I, phi, w_ref, TL = ref(t)
        iref = (I * math.cos(phi), I * math.sin(phi))
        ff = (0.0, 0.0)
        if c["ff"]:
            ff = (-m["Kt"] * w_ref * math.sin(phi), m["Kt"] * w_ref * math.cos(phi))
        vu, e = current_pi(iref, (x[0], x[1]), integ, ff, g)
        vsat, duty, ksc = bridge_avg(vu, brd["vbus"], brd["topology"])
        integ = pi_update(integ, e, vu, vsat, g)
        if c["delay"]:
            v_apply, d_apply, en = v_hold, d_hold, en_hold
        else:
            v_apply, d_apply, en = vsat, duty, True
        v_hold, d_hold, en_hold = vsat, duty, True
        log[k] = [t, x[0], x[1], x[2], x[3], iref[0], iref[1], v_apply[0], v_apply[1], ksc, I, phi]
        if brd["stage"] == "switching":
            x, ext[k] = period_sw(x, d_apply, en, TL, m, brd["vbus"], brd["topology"],
                                  brd["sw"], Ts, locked)
        else:
            h = Ts / c["nsub"]
            for _ in range(c["nsub"]):
                x = rk4(x, (v_apply[0], v_apply[1], TL), m, h, locked)
            ext[k] = [x[0], x[0], x[1], x[1], v_apply[0], v_apply[1]]
    return log, ext


